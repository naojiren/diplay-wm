package com.shilapi.xcertplay

import android.bluetooth.BluetoothAdapter
import android.content.Context
import android.content.ContextWrapper
import com.shilapi.xcertplay.orchestration.WirelessHotspotMode
import org.junit.Assert.*
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.Shadows.shadowOf
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [23, 28], manifest = Config.NONE)
class WmEx5StartupTest {
    private val base get() = RuntimeEnvironment.getApplication()
    private val wm get() = object : ContextWrapper(base) { override fun getPackageName() = WmEx5PerformanceProfile.PACKAGE }
    @Before fun clear() {
        for (name in listOf("xcertplay_airplay", "diplay_wm_ex5_performance", "diplay_wm_ex5_cluster"))
            base.getSharedPreferences(name, Context.MODE_PRIVATE).edit().clear().commit()
    }
    @Test fun defaultsReachBothDisplayAndInstrumentAndRemainEditable() {
        assertEquals(18, AirPlayPersistence.loadFps(wm))
        assertEquals(50, AirPlayPersistence.loadDisplayScalePercent(wm))
        AirPlayPersistence.saveWirelessHotspotMode(wm, WirelessHotspotMode.MANUAL)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(WirelessHotspotMode.WIFI_P2P, AirPlayPersistence.loadWirelessHotspotMode(wm))
        assertEquals(18, AirPlayPersistence.loadFps(wm))
        assertEquals(50, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertEquals(44, WmEx5PerformanceProfile.channel(wm))
        assertEquals(24, WmEx5ClusterProfile.margin(wm, "left"))
        assertEquals(5, WmEx5ClusterProfile.margin(wm, "bottom"))
        assertTrue(WmEx5ClusterProfile.enabled(wm))
        assertEquals(100, WmEx5ClusterProfile.resolutionPercent(wm))
        assertEquals(18, WmEx5ClusterProfile.fps(wm))
        assertTrue(AirPlayPersistence.loadClusterMapEnabled(wm))
        assertFalse(AirPlayPersistence.loadAdbClusterEnabled(wm))
        assertFalse(AirPlayPersistence.loadHevcEnabled(wm))
        AirPlayPersistence.saveFps(wm, 4)
        AirPlayPersistence.saveDisplayScalePercent(wm, 55)
        WmEx5ClusterProfile.setEnabled(wm, false)
        AirPlayPersistence.saveClusterMapEnabled(wm, false)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(18, AirPlayPersistence.loadFps(wm))
        assertEquals(55, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertFalse(WmEx5ClusterProfile.enabled(wm))
        assertFalse(AirPlayPersistence.loadClusterMapEnabled(wm))
    }
    @Test fun historicalInitializationKeepsSavedModeAndAudioBeforePerf18Migration() {
        AirPlayPersistence.saveFps(wm, 60)
        AirPlayPersistence.saveDisplayScalePercent(wm, 100)
        AirPlayPersistence.saveHevcEnabled(wm, true)
        WmEx5ClusterProfile.setEnabled(wm, false)
        WmEx5ClusterProfile.setMargin(wm, "left", 10)
        AirPlayPersistence.saveWirelessHotspotMode(wm, WirelessHotspotMode.EXISTING_WIFI)
        WmEx5PerformanceProfile.saveChannel(wm, 1)
        AirPlayPersistence.saveMediaBufferMillis(wm, 160)
        val audio = AirPlayPersistence.loadMediaBufferMillis(wm)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(18, AirPlayPersistence.loadFps(wm))
        assertEquals(50, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertTrue(WmEx5ClusterProfile.enabled(wm))
        assertEquals(24, WmEx5ClusterProfile.margin(wm, "left"))
        assertEquals(44, WmEx5PerformanceProfile.channel(wm))
        assertEquals(WirelessHotspotMode.EXISTING_WIFI, AirPlayPersistence.loadWirelessHotspotMode(wm))
        assertEquals(audio, AirPlayPersistence.loadMediaBufferMillis(wm))
    }
    @Test fun perf3UpgradeChangesOnlyResolutionAndFpsOnce() {
        wm.getSharedPreferences("diplay_wm_ex5_performance", Context.MODE_PRIVATE).edit()
            .putBoolean("perf3_defaults_applied", true).putBoolean("perf11_layout_defaults_applied", true).commit()
        AirPlayPersistence.saveFps(wm, 18)
        AirPlayPersistence.saveDisplayScalePercent(wm, 45)
        AirPlayPersistence.saveHevcEnabled(wm, true)
        WmEx5ClusterProfile.setEnabled(wm, false)
        WmEx5ClusterProfile.setMargin(wm, "left", 15)
        AirPlayPersistence.saveWirelessHotspotMode(wm, WirelessHotspotMode.EXISTING_WIFI)
        WmEx5PerformanceProfile.saveChannel(wm, 1)
        AirPlayPersistence.saveMediaBufferMillis(wm, 160)
        val audio = AirPlayPersistence.loadMediaBufferMillis(wm)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(18, AirPlayPersistence.loadFps(wm))
        assertEquals(40, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertTrue(AirPlayPersistence.loadHevcEnabled(wm))
        assertFalse(WmEx5ClusterProfile.enabled(wm))
        assertEquals(15, WmEx5ClusterProfile.margin(wm, "left"))
        assertEquals(WirelessHotspotMode.EXISTING_WIFI, AirPlayPersistence.loadWirelessHotspotMode(wm))
        assertEquals(1, WmEx5PerformanceProfile.channel(wm))
        assertEquals(audio, AirPlayPersistence.loadMediaBufferMillis(wm))
        AirPlayPersistence.saveFps(wm, 4)
        AirPlayPersistence.saveDisplayScalePercent(wm, 50)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(18, AirPlayPersistence.loadFps(wm))
        assertEquals(50, AirPlayPersistence.loadDisplayScalePercent(wm))
    }
    @Test fun perf4UpgradeOnlyInitializesClusterAndPreservesSubsequentChoices() {
        wm.getSharedPreferences("diplay_wm_ex5_performance", Context.MODE_PRIVATE).edit()
            .putBoolean("perf3_defaults_applied", true).putBoolean("perf4_defaults_applied", true)
            .putBoolean("perf11_layout_defaults_applied", true).commit()
        AirPlayPersistence.saveFps(wm, 12)
        AirPlayPersistence.saveDisplayScalePercent(wm, 45)
        WmEx5ClusterProfile.setMargin(wm, "left", 15)
        WmEx5ClusterProfile.setEnabled(wm, false)
        AirPlayPersistence.saveWirelessHotspotMode(wm, WirelessHotspotMode.EXISTING_WIFI)
        AirPlayPersistence.saveMediaBufferMillis(wm, 160)
        val audio = AirPlayPersistence.loadMediaBufferMillis(wm)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(100, WmEx5ClusterProfile.resolutionPercent(wm))
        assertEquals(18, WmEx5ClusterProfile.fps(wm))
        assertFalse(WmEx5ClusterProfile.nativeSize(wm))
        assertEquals(12, AirPlayPersistence.loadFps(wm))
        assertEquals(45, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertEquals(15, WmEx5ClusterProfile.margin(wm, "left"))
        assertFalse(WmEx5ClusterProfile.enabled(wm))
        assertEquals(WirelessHotspotMode.EXISTING_WIFI, AirPlayPersistence.loadWirelessHotspotMode(wm))
        assertEquals(audio, AirPlayPersistence.loadMediaBufferMillis(wm))
        WmEx5ClusterProfile.setResolutionPercent(wm, 50)
        WmEx5ClusterProfile.setFps(wm, 24)
        WmEx5ClusterProfile.setNativeSize(wm, true)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(50, WmEx5ClusterProfile.resolutionPercent(wm))
        assertEquals(24, WmEx5ClusterProfile.fps(wm))
        assertTrue(WmEx5ClusterProfile.nativeSize(wm))
    }

    @Test fun otherPackagesKeepTheirDefaults() {
        WmEx5Startup.applyDefaults(base)
        assertEquals(30, AirPlayPersistence.loadFps(base))
        assertEquals(100, AirPlayPersistence.loadDisplayScalePercent(base))
        assertFalse(WmEx5ClusterProfile.enabled(base))
        assertFalse(AirPlayPersistence.loadClusterMapEnabled(base))
    }
    @Test fun perf5UpgradeChangesManufacturerOnceAndKeepsDriverChoices() {
        wm.getSharedPreferences("diplay_wm_ex5_performance", Context.MODE_PRIVATE).edit()
            .putBoolean("perf3_defaults_applied", true).putBoolean("perf4_defaults_applied", true)
            .putBoolean("perf5_cluster_defaults_applied", true).putBoolean("perf11_layout_defaults_applied", true).commit()
        AirPlayPersistence.saveManufacturer(wm, "DiPlay")
        AirPlayPersistence.saveFps(wm, 12)
        AirPlayPersistence.saveDisplayScalePercent(wm, 45)
        AirPlayPersistence.saveWirelessHotspotMode(wm, WirelessHotspotMode.EXISTING_WIFI)
        WmEx5PerformanceProfile.saveChannel(wm, 44)
        WmEx5ClusterProfile.setResolutionPercent(wm, 50)
        WmEx5ClusterProfile.setFps(wm, 24)
        WmEx5Startup.applyDefaults(wm)
        assertEquals("威马", AirPlayPersistence.loadManufacturer(wm))
        assertEquals(12, AirPlayPersistence.loadFps(wm))
        assertEquals(45, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertEquals(44, WmEx5PerformanceProfile.channel(wm))
        assertEquals(50, WmEx5ClusterProfile.resolutionPercent(wm))
        assertEquals(24, WmEx5ClusterProfile.fps(wm))
        assertEquals(WirelessHotspotMode.EXISTING_WIFI, AirPlayPersistence.loadWirelessHotspotMode(wm))
        AirPlayPersistence.saveManufacturer(wm, "Custom")
        WmEx5Startup.applyDefaults(wm)
        assertEquals("Custom", AirPlayPersistence.loadManufacturer(wm))
    }
    @Test fun perf10UpgradeAppliesLayoutOnceAndKeepsConnectionAudioAndInstrumentChoices() {
        wm.getSharedPreferences("diplay_wm_ex5_performance", Context.MODE_PRIVATE).edit()
            .putBoolean("perf3_defaults_applied", true).putBoolean("perf4_defaults_applied", true)
            .putBoolean("perf5_cluster_defaults_applied", true).putBoolean("perf6_manufacturer_applied", true).commit()
        AirPlayPersistence.saveFps(wm, 8)
        AirPlayPersistence.saveDisplayScalePercent(wm, 40)
        AirPlayPersistence.saveWirelessHotspotMode(wm, WirelessHotspotMode.EXISTING_WIFI)
        AirPlayPersistence.saveExistingWifiCredentials(wm, "PDCN_5G", "test-password")
        AirPlayPersistence.saveMediaBufferMillis(wm, 160)
        val audio = AirPlayPersistence.loadMediaBufferMillis(wm)
        WmEx5PerformanceProfile.saveChannel(wm, 36)
        WmEx5ClusterProfile.setEnabled(wm, true)
        WmEx5ClusterProfile.setMargin(wm, "top", 3)
        WmEx5ClusterProfile.setMargin(wm, "right", 7)
        WmEx5ClusterProfile.setResolutionPercent(wm, 100)
        WmEx5ClusterProfile.setFps(wm, 18)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(18, AirPlayPersistence.loadFps(wm))
        assertEquals(50, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertEquals(44, WmEx5PerformanceProfile.channel(wm))
        assertEquals(24, WmEx5ClusterProfile.margin(wm, "left"))
        assertEquals(5, WmEx5ClusterProfile.margin(wm, "bottom"))
        assertEquals(3, WmEx5ClusterProfile.margin(wm, "top"))
        assertEquals(7, WmEx5ClusterProfile.margin(wm, "right"))
        assertEquals(100, WmEx5ClusterProfile.resolutionPercent(wm))
        assertEquals(18, WmEx5ClusterProfile.fps(wm))
        assertTrue(WmEx5ClusterProfile.enabled(wm))
        assertEquals(WirelessHotspotMode.EXISTING_WIFI, AirPlayPersistence.loadWirelessHotspotMode(wm))
        assertEquals("PDCN_5G", AirPlayPersistence.loadExistingWifiSsid(wm))
        assertEquals("test-password", AirPlayPersistence.loadExistingWifiPassphrase(wm))
        assertEquals(audio, AirPlayPersistence.loadMediaBufferMillis(wm))
        AirPlayPersistence.saveFps(wm, 12)
        AirPlayPersistence.saveDisplayScalePercent(wm, 45)
        WmEx5PerformanceProfile.saveChannel(wm, 44)
        WmEx5ClusterProfile.setMargin(wm, "left", 10)
        WmEx5ClusterProfile.setMargin(wm, "bottom", 2)
        WmEx5Startup.applyDefaults(wm)
        assertEquals(12, AirPlayPersistence.loadFps(wm))
        assertEquals(45, AirPlayPersistence.loadDisplayScalePercent(wm))
        assertEquals(44, WmEx5PerformanceProfile.channel(wm))
        assertEquals(10, WmEx5ClusterProfile.margin(wm, "left"))
        assertEquals(2, WmEx5ClusterProfile.margin(wm, "bottom"))
    }

    @Test fun openingEx5EnablesAnOffBluetoothAdapter() {
        val adapter = BluetoothAdapter.getDefaultAdapter()
        assertNotNull(adapter)
        shadowOf(adapter).setState(BluetoothAdapter.STATE_OFF)
        WmEx5Startup.enableBluetooth(wm)
        assertTrue(adapter.isEnabled)
        WmEx5Startup.enableBluetooth(wm)
        assertTrue(adapter.isEnabled)
    }
    @Test fun otherPackagesDoNotTurnOnBluetooth() {
        val adapter = BluetoothAdapter.getDefaultAdapter()
        shadowOf(adapter).setState(BluetoothAdapter.STATE_OFF)
        WmEx5Startup.enableBluetooth(base)
        assertFalse(adapter.isEnabled)
    }
}
